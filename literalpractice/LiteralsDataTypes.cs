using System;
using System.Collections.Generic;
using System.Text;

namespace C_Practise.stringpractice
{
    public class LiteralsDataTypes
    {
        public static void PrintData()
        {
           //Char data type
            Console.WriteLine('b');

            //Integer
            Console.WriteLine(123);

            //Float -> f ->literal suffix
            Console.WriteLine(0.1125F);

            //double
            Console.WriteLine(0.25);

            //decimal
            Console.WriteLine(12.39816m);

            //Boolean
            Console.WriteLine(true);
            Console.WriteLine(false);
        }
    }
}
